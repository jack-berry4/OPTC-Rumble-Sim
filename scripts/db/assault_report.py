"""Write docs/ASSAULT_DATA.md: what the game's master database keeps on the current (or a given) Assault Rumble
season's boss teams and units, for the Assault accuracy work (user, 2026-11-23). Reads OPTC Decomp/master_db_tool/
sakura.db (OPTC_GAME_DIR overrides the folder).

    python -I scripts/db/assault_report.py [season id]
"""
import json
import os
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DB = Path(os.environ.get("OPTC_GAME_DIR") or ROOT.parent / "OPTC Decomp" / "master_db_tool") / "sakura.db"
OUT = ROOT / "docs" / "ASSAULT_DATA.md"
TYPES = {1: "STR", 2: "DEX", 3: "QCK", 4: "PSY", 5: "INT"}
CLASSES = {1: "Fighter", 2: "Slasher", 3: "Striker", 4: "Shooter", 5: "Free Spirit", 6: "Cerebral", 7: "Powerhouse", 8: "Driven"}
STYLES = {0: "BAL", 1: "ATK", 2: "DEF", 3: "RCV", 4: "SPT", 5: "DBF"}


def main() -> int:
    c = sqlite3.connect(str(DB))
    c.row_factory = sqlite3.Row
    q = lambda sql, *a: c.execute(sql, a).fetchall()  # noqa: E731
    one = lambda sql, *a: c.execute(sql, a).fetchone()  # noqa: E731
    ev = one("select * from MstAssaultRumbleEvent_ where serverId_ = ?", int(sys.argv[1])) if len(sys.argv) > 1 else one("select * from MstAssaultRumbleEvent_ order by startAt_ desc limit 1")
    rule = json.loads(ev["ruleJson_"] or "{}")
    eff = json.loads(ev["effectsJson_"] or "{}")
    beh = {r["serverId_"]: r["name_"] for r in q("select serverId_, name_ from MstPiratesBehavior_")}
    lines = [
        f"# Assault Rumble: game data of season {ev['serverId_']}",
        "",
        f"Generated by `scripts/db/assault_report.py` from the game's master database. Season {ev['serverId_']}: "
        f"start {ev['startAt_']}, end {ev['endAt_']} (unix). Boss teams in order: {ev['assaultRumbleBossIdSequencesJson_']}.",
        "",
        "## Rule",
        "",
        f"- `ruleJson_`: {json.dumps({k: v for k, v in rule.items() if not k.startswith('description_')}, ensure_ascii=False)}",
        f"- effects: {eff.get('description', '')}",
        "",
        "## What sets bosses apart (all seasons' boss units)",
        "",
        "- A boss is its own character entry (logbook -1), not the playable unit: its own stats, Rumble special / ability,",
        "  behavior pattern, style, speed and DEF. Its server id ends in the server id of the playable form it copies",
        "  (2412210 -> 12210 = the 6* Borsalino), the only link to that unit (the app's portrait; else the same",
        "  main-game special and rarity). The deck gives each unit level 99, main special level 6, Rumble special 10,",
        "  ability 5, plus 600/600/600 (Lv 9-10 decks; 0 below), Limit Break 40, potentials 5/5/5, sockets 5x5 and",
        "  its ATK / HP / RCV; the Assault level multiplies HP / ATK / RCV by the `EnemyLevel` coefficients.",
        "- Its stats [measured 2026-11-24 on the Lv 10 stat screens and Damage over Time ticks]: deck stat x (1 +",
        "  k x f) x the level coefficient, k = 1.5% HP / 0.75% ATK / 0.25% RCV, f = (potentials + sockets) x main",
        "  special level / its max (Fujitora 6 of 8: 30 of 40). The plus values do NOT count.",
        "- `piratesAbilityId_` (its resistance) is a shared boss package: immune to Forced Out and Special Bind (and",
        "  Confusion or Action Bind), and **85% less percentage damage** (`DamagePercentReduction` 0.85).",
        "- `piratesLimitBreakAbilityId_` 497 / 498: 5% less damage from QCK / STR.",
        "- `additionalBehaviorCount_` (per deck): the first unit (position 1, the main boss) holds 1 + count places in",
        "  the NEXT queue (Blackbeard 4, Akainu 3, measured in the videos); it still takes one turn at a time, and",
        "  several of the player's units may attack it at once. The other units of the team are regular (one place,",
        "  one attacker at a time). The videos label every enemy BOSS. See docs/ASSAULT_RUNS.md.",
        "- Behaviors 10004-10009 = Small / Medium Range Normal / Power / Full Attack: the boss walks up to its target as",
        "  for an attack, skips the Damage over Time and Paralysis checks, hits every enemy in range, walks back.",
        "",
    ]
    for lv in q("select * from MstAssaultRumbleEventEnemyLevel_ where assaultRumbleEventId_ = ? and level_ = 10 order by assaultRumbleBossId_", ev["serverId_"]):
        d = one("select * from MstAssaultRumbleEnemyDeck_ where serverId_ = ?", lv["assaultRumbleEnemyDeckId_"])
        levels = q("select level_, staminaCoefficient_, attackCoefficient_, healingCoefficient_ from MstAssaultRumbleEventEnemyLevel_ where assaultRumbleEventId_ = ? and assaultRumbleBossId_ = ? order by level_", ev["serverId_"], lv["assaultRumbleBossId_"])
        deck = one("select * from MstPiratesNpcUserPiratesDeck_ where piratesNpcUserId_ = ?", d["piratesNpcUserId_"])
        units = q("select dc.position_, dc.characterType_, uc.* from MstPiratesNpcUserPiratesDeckCharacter_ dc join MstPiratesNpcUserCharacter_ uc on uc.serverId_ = dc.piratesNpcUserCharacterId_ where dc.piratesNpcUserPiratesDeckId_ = ? order by dc.position_", deck["serverId_"])
        lines += [f"## Boss team {lv['assaultRumbleBossId_']} (deck {d['serverId_']}): {len(units)} unit{'s' if len(units) != 1 else ''}, additional behaviors {d['additionalBehaviorCount_']}", ""]
        lines.append("Assault level coefficients (HP / ATK / RCV): " + ", ".join(f"Lv{r['level_']} {r['staminaCoefficient_']}/{r['attackCoefficient_']}/{r['healingCoefficient_']}" for r in levels))
        lines.append("")
        for u in units:
            ch = one("select * from MstCharacter_ where serverId_ = ?", u["characterId_"])
            pas = one("select description_ from MstPiratesPassiveSkillEffect_ where piratesPassiveSkillId_ = ? order by level_ desc limit 1", ch["piratesPassiveSkillId_"])
            act = one("select description_, chargeIntervalTime_, limit_ from MstPiratesActiveSkillEffect_ where piratesActiveSkillId_ = ? order by level_ desc limit 1", ch["piratesActiveSkillId_"])
            res = one("select description_ from MstPiratesAbility_ where serverId_ = ?", ch["piratesAbilityId_"])
            pat = json.loads(ch["piratesBehaviorPatternsJson_"] or "{}").get("data", [])
            play = one("select logbookId_, subName_, piratesSpeed_, piratesDefense_ from MstCharacter_ where name_ = ? and logbookId_ > 0 and piratesActiveSkillId_ > 0 order by logbookId_ desc limit 1", ch["name_"])
            lines += [
                f"### Position {u['position_']}: {ch['name_']} - {ch['subName_']} (character {u['characterId_']})",
                "",
                f"- {TYPES.get(ch['attributeId_'], ch['attributeId_'])}, {CLASSES.get(ch['characterType_'], ch['characterType_'])} / {CLASSES.get(ch['subCharacterType_'], ch['subCharacterType_'])}, style {STYLES.get(ch['piratesStyle_'], ch['piratesStyle_'])}, SPD {ch['piratesSpeed_']}, DEF {ch['piratesDefense_']}, cost {ch['piratesDeckCost_']}"
                + (f" (playable #{play['logbookId_']} {play['subName_']}: SPD {play['piratesSpeed_']}, DEF {play['piratesDefense_']})" if play else ""),
                f"- deck stats: ATK {u['attack_']}, HP {u['stamina_']}, RCV {u['healing_']}; level {u['level_']}, special {u['piratesActiveSkillLevel_']}, ability {u['piratesPassiveSkillLevel_']}",
                f"- behaviors: " + "; ".join(f"target {p.get('target_type')}, if {json.dumps(p.get('conditions'))}: " + " → ".join(beh.get(b, str(b)) for b in p.get("behavior_ids", [])) for p in pat),
                f"- resistance ({ch['piratesAbilityId_']}): {res['description_'] if res else '-'}",
                f"- ability: {pas['description_'] if pas else '-'}",
            ]
            if act:
                lines.append(f"- special (CT {act['chargeIntervalTime_']} s, uses {act['limit_']}): {act['description_']}")
            lines.append("")
    score = q("select characterId_, coefficient_ from MstAssaultRumbleEventCharacterScore_ where assaultRumbleEventId_ = ?", ev["serverId_"])
    if score:
        lines += ["## Score bonus units (trusty)", ""]
        for s in score:
            ch = one("select name_, subName_, logbookId_ from MstCharacter_ where serverId_ = ?", s["characterId_"])
            lines.append(f"- #{ch['logbookId_'] if ch else '?'} {ch['name_'] if ch else s['characterId_']}{' - ' + ch['subName_'] if ch and ch['subName_'] else ''}: x{s['coefficient_']}")
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
